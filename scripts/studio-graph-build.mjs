// Builds the studio's model graph bundle: React Flow and its stylesheet, as two
// strings the studio page serves inline. Kept apart from the page so the React
// code can be a real component instead of a template-literal string.
import { join } from "node:path";
import { build } from "esbuild";

const HEADER = "// Generated by scripts/gen-studio-graph.mjs from src/studio/graph.tsx. Do not edit.\n";

/** The generated module: the bundle and the stylesheet, both as string literals. */
export async function buildGraph(root) {
  const js = await build({
    entryPoints: [join(root, "src", "studio", "graph.tsx")],
    bundle: true,
    write: false,
    minify: true,
    format: "iife",
    target: "es2020",
    jsx: "automatic",
    // The stylesheet is bundled separately below, so the import in the component
    // must not try to resolve to a file in the page's world.
    loader: { ".css": "empty" },
    define: { "process.env.NODE_ENV": '"production"' },
    logLevel: "silent",
  });

  const css = await build({
    entryPoints: [join(root, "node_modules", "@xyflow", "react", "dist", "style.css")],
    bundle: true,
    write: false,
    minify: true,
    logLevel: "silent",
  });

  // With write:false and no outfile, esbuild reports one file per build.
  const script = js.outputFiles?.[0]?.text ?? "";
  const style = css.outputFiles?.[0]?.text ?? "";
  if (script === "" || style === "") throw new Error("The graph bundle came back empty.");

  // The bundle is inlined in the page, so a literal closing tag inside it (React
  // carries a few as strings) would end the element early and break the document.
  // Both forms: React carries the literal tag in a string, and either one would
  // end the element early. \u003C is the same character to the JS parser.
  const inline = (text) =>
    text.replace(/<\/(script|style)/gi, "<\\/$1").replace(/<(script|style)/gi, "\\u003C$1");
  return `${HEADER}export const GRAPH_JS = ${JSON.stringify(inline(script))};\nexport const GRAPH_CSS = ${JSON.stringify(inline(style))};\n`;
}
