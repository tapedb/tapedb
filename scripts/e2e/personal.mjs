import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { createClient } from "@tapedb/tapedb";
import { BASE, s, until } from "./common.mjs";
const workspace = randomUUID();
const db = createClient({ schema: s, url: BASE, workspace });
const created = await db.person.create({ data: { name: "Private Alice", data: { secret: "private payload" } } });
const rows = await db.person.findMany();
assert.equal(rows[0].name, "Private Alice");
assert.deepEqual(rows[0].data, { secret: "private payload" });
const seen = [];
const unsubscribe = db.person.findMany().subscribe(result => result.data && seen.push(result.data));
await until(() => seen.some(rows => rows[0]?.name === "Private Alice"), "live plaintext", seen);
const exported = [];
for await (const line of db.$export()) exported.push(line);
assert.ok(exported.some(line => line.type === "row" && line.data.name === "Private Alice"));
await db.$erasePerson(rows[0].id);
const erased = await db.person.findMany();
assert.equal(erased[0].name, null);
assert.deepEqual(erased[0].$erased, ["name", "data"]);
await until(() => seen.some(rows => rows[0]?.name === null && rows[0]?.$erased?.includes("name")), "live erasure", seen);
unsubscribe(); db.$close();
console.log("personal: encrypted writes, exports and live erasure passed");
