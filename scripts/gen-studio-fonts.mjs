// Writes src/studio/fonts.gen.ts from assets/fonts: the studio's brand fonts as
// base64, so a deployed Worker can serve them with no files. Run after
// changing a font: node scripts/gen-studio-fonts.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const names = ["space-grotesk", "inter", "jetbrains-mono"];
const lines = names.map((name) => `  "${name}.woff2": "${readFileSync(join(root, "assets", "fonts", `${name}.woff2`)).toString("base64")}",`);
writeFileSync(
  join(root, "src", "studio", "fonts.gen.ts"),
  `// Generated by scripts/gen-studio-fonts.mjs from assets/fonts. Do not edit.\n// Space Grotesk, Inter and JetBrains Mono: SIL Open Font License 1.1 (assets/fonts/OFL.txt).\nexport const FONTS: Readonly<Record<string, string>> = {\n${lines.join("\n")}\n};\n`
);
