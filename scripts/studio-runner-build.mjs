// Builds the source of src/studio/runner.gen.ts. Shared by the generator and
// the test that checks the checked-in file is current.
import { join } from "node:path";
import { build } from "esbuild";

export async function buildRunner(root) {
  const result = await build({
    entryPoints: [join(root, "src", "studio", "runner.ts")],
    bundle: true,
    format: "iife",
    globalName: "tapedbRunner",
    target: "es2022",
    minify: true,
    legalComments: "none",
    write: false,
    logLevel: "silent",
  });
  const code = result.outputFiles[0].text.trim();
  return `// Generated by scripts/gen-studio-runner.mjs from src/studio/runner.ts. Do not edit.\nexport const RUNNER = ${JSON.stringify(code)};\n`;
}
